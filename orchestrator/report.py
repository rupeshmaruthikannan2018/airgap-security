def format_epss_score(score):
    if score is None:
        return "Unavailable"
    try:
        f_val = float(score)
        s = f"{f_val:.5f}"
        if s.endswith("0") and len(s.split(".")[1]) == 5:
            return s[:-1]
        return s
    except Exception:
        return str(score)


