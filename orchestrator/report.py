# Preserve the original generator and wrap it with sidecar discovery.
_prototype_original_generate_html_report = generate_html_report


def generate_html_report(findings, application_name, output_file):
    if isinstance(findings, dict) and 'findings' in findings:
        findings = findings['findings']
    elif not isinstance(findings, list):
        findings = list(findings) if findings else []
    sidecars = _prototype_load_sidecars(output_file)

    enriched = [
        _prototype_enrich_finding(finding, sidecars)
        for finding in findings
    ]

    return _prototype_original_generate_html_report(
        enriched,
        application_name,
        output_file
    )

