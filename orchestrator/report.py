def severity_class(severity):
    severity = (severity or "UNKNOWN").upper()

    if severity in ["CRITICAL", "HIGH", "ERROR"]:
        return "high"

    if severity in ["MEDIUM", "WARNING"]:
        return "medium"

    if severity in ["LOW", "INFO"]:
        return "low"

    return "unknown"


def normalize_severity(severity):
    severity = (severity or "UNKNOWN").upper()

    if severity == "ERROR":
        return "HIGH"

    if severity == "WARNING":
        return "MEDIUM"

    if severity not in [
        "CRITICAL",
        "HIGH",
        "MEDIUM",
        "LOW",
        "UNKNOWN"
    ]:
        return "UNKNOWN"

    return severity


