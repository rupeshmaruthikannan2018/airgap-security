# Automatically discovers contextual sidecar files and renders
# deterministic environment conditions separately from LLM reasoning.


def _prototype_load_json(path):
    try:
        path = Path(path)
        if not path.exists():
            return None
        with open(path, 'r', encoding='utf-8') as f:
            return json.load(f)
    except Exception:
        return None


def _prototype_contextual_assessment(obj):
    if isinstance(obj, dict):
        strong = {
            'applicability', 'conditions', 'rce_assessment',
            'information_disclosure_assessment', 'root_cause',
            'validation', 'unknowns'
        }
        if len(strong.intersection(obj.keys())) >= 2:
            return obj

        for key in [
            'remediation_assessment', 'remediation_analysis',
            'llm_assessment', 'assessment', 'result', 'analysis', 'data'
        ]:
            if key in obj:
                found = _prototype_contextual_assessment(obj[key])
                if found is not None:
                    return found

        for value in obj.values():
            found = _prototype_contextual_assessment(value)
            if found is not None:
                return found

    elif isinstance(obj, list):
        for value in obj:
            found = _prototype_contextual_assessment(value)
            if found is not None:
                return found

    return None


def _prototype_condition_records(obj, records=None):
    if records is None:
        records = []

    if isinstance(obj, dict):
        is_condition = (
            ('condition' in obj or 'name' in obj or 'condition_id' in obj)
            and 'status' in obj
        )

        if is_condition:
            evidence = (
                obj.get('selected_evidence')
                or obj.get('evidence')
                or obj.get('all_evidence')
            )
            records.append({
                'name': (
                    obj.get('condition')
                    or obj.get('name')
                    or obj.get('condition_id')
                    or 'Condition'
                ),
                'status': obj.get('status', 'UNKNOWN'),
                'reason': obj.get('reason') or obj.get('description') or '',
                'evidence': evidence,
                'required': (
                    obj.get('required_value')
                    if 'required_value' in obj
                    else obj.get('required')
                )
            })

        for value in obj.values():
            _prototype_condition_records(value, records)

    elif isinstance(obj, list):
        for value in obj:
            _prototype_condition_records(value, records)

    unique = []
    seen = set()
    for record in records:
        key = (
            str(record.get('name')),
            str(record.get('status')),
            json.dumps(record.get('evidence'), sort_keys=True, default=str)
        )
        if key not in seen:
            seen.add(key)
            unique.append(record)
    return unique


def _prototype_group_statuses(obj, groups=None):
    if groups is None:
        groups = []

    if isinstance(obj, dict):
        for key, value in obj.items():
            if isinstance(value, dict):
                status = value.get('overall_status') or value.get('status')
                lowered = str(key).lower()
                if status and any(
                    x in lowered for x in [
                        'remote_code_execution',
                        'information_disclosure',
                        'content_injection'
                    ]
                ):
                    groups.append((key, status, value.get('reason', '')))
                _prototype_group_statuses(value, groups)
            elif isinstance(value, list):
                _prototype_group_statuses(value, groups)

    elif isinstance(obj, list):
        for value in obj:
            _prototype_group_statuses(value, groups)

    return groups


def _prototype_render_evidence(value):
    if value is None:
        return '<span class="muted">No evidence</span>'

    if isinstance(value, dict):
        path = value.get('path')
        actual_value = value.get('value')
        evidence_status = value.get('status')
        parts = []

        if path:
            parts.append(f'<b>{safe_text(path)}</b>')
        if 'value' in value:
            parts.append(f'Value: {safe_text(actual_value)}')
        if evidence_status:
            parts.append(f'Evidence: {status_badge(evidence_status)}')
        if parts:
            return '<br>'.join(parts)

    return safe_text(value)


def _prototype_render_deterministic_evaluation(evaluation):
    if not evaluation:
        return ''

    records = _prototype_condition_records(evaluation)
    groups = _prototype_group_statuses(evaluation)

    if not records and not groups:
        return ''

    html = '''
    <section class="deterministic-evaluation">
        <div class="evaluation-banner">
            <b>Deterministic Environment Evaluation</b>
            <span>
                These statuses are calculated from collected environment
                evidence before LLM remediation reasoning.
            </span>
        </div>
    '''

    if groups:
        html += '<div class="assessment-grid evaluator-groups">'
        for name, status, reason in groups:
            title = str(name).replace('_', ' ').title()
            html += f'''
            <div class="assessment-card">
                <div class="assessment-header">
                    <h4>{escape(title)}</h4>
                    {status_badge(status)}
                </div>
                {f"<p>{safe_text(reason)}</p>" if reason else ""}
            </div>
            '''
        html += '</div>'

    if records:
        html += '''
        <div class="condition-table-wrapper">
            <table class="condition-table">
                <thead>
                    <tr>
                        <th>Environmental Condition</th>
                        <th>Status</th>
                        <th>Required</th>
                        <th>Evidence</th>
                    </tr>
                </thead>
                <tbody>
        '''

        for record in records:
            reason_html = ''
            if record.get('reason'):
                reason_html = (
                    '<div class="small-text">'
                    + safe_text(record['reason'])
                    + '</div>'
                )

            required = record.get('required')
            required_html = (
                safe_text(required)
                if required is not None
                else '<span class="muted">N/A</span>'
            )

            html += f'''
                    <tr>
                        <td>
                            <b>{safe_text(record['name'])}</b>
                            {reason_html}
                        </td>
                        <td>{status_badge(record['status'])}</td>
                        <td>{required_html}</td>
                        <td>{_prototype_render_evidence(record['evidence'])}</td>
                    </tr>
            '''

        html += '''
                </tbody>
            </table>
        </div>
        '''

    html += '</section>'
    return html


def _prototype_load_sidecars(output_file):
    base = Path(output_file).parent
    candidates = {
        'evaluation': [
            base / 'cve-evaluation.json',
            base / 'cve_evaluation.json',
            base / 'evaluation.json'
        ],
        'remediation': [
            base / 'remediation-analysis.json',
            base / 'remediation_analysis.json',
            base / 'remediation.json'
        ],
        'configuration': [
            base / 'tomcat-config.json',
            base / 'tomcat_config.json',
            base / 'configuration.json'
        ],
        'validation': [
            base / 'remediation-validation-after.json',
            base / 'remediation-validation.json',
            base / 'validation.json'
        ]
    }

    loaded = {}
    for category, paths in candidates.items():
        loaded[category] = None
        for path in paths:
            data = _prototype_load_json(path)
            if data is not None:
                loaded[category] = data
                break
    return loaded


def _prototype_normalize_cve(value):
    if isinstance(value, str):
        value = value.strip().upper()
        return value if value.startswith("CVE-") else None

    if isinstance(value, dict):
        for key in ("cve", "cve_id", "CVE", "vulnerability_id", "VulnerabilityID"):
            normalized = _prototype_normalize_cve(value.get(key))
            if normalized:
                return normalized

    return None


def _prototype_finding_cve(finding):
    if not isinstance(finding, dict):
        return None

    for key in (
        "cve",
        "cve_id",
        "CVE",
        "vulnerability_id",
        "VulnerabilityID",
    ):
        normalized = _prototype_normalize_cve(finding.get(key))
        if normalized:
            return normalized

    return None


def _prototype_sidecar_cve(sidecar):
    if not isinstance(sidecar, dict):
        return None

    for key in (
        "cve",
        "cve_id",
        "CVE",
        "vulnerability_id",
        "VulnerabilityID",
    ):
        normalized = _prototype_normalize_cve(sidecar.get(key))
        if normalized:
            return normalized

    condition_evaluation = sidecar.get("condition_evaluation")
    if isinstance(condition_evaluation, dict):
        normalized = _prototype_normalize_cve(
            condition_evaluation.get("cve_id")
        )
        if normalized:
            return normalized

    remediation_analysis = sidecar.get("remediation_analysis")
    if isinstance(remediation_analysis, dict):
        for key in (
            "cve",
            "cve_id",
            "CVE",
            "vulnerability_id",
            "VulnerabilityID",
        ):
            normalized = _prototype_normalize_cve(
                remediation_analysis.get(key)
            )
            if normalized:
                return normalized

    return None


def _prototype_enrich_finding(finding, sidecars):
    enriched = dict(finding)

    # If finding already contains contextual analysis, unpack its components
    if "contextual_cve_analysis" in finding:
        ctx = finding["contextual_cve_analysis"]
        if isinstance(ctx, dict):
            if "condition_evaluation" in ctx:
                enriched.setdefault("cve_evaluation", ctx["condition_evaluation"])
            if "remediation_analysis" in ctx:
                enriched.setdefault("remediation_analysis", ctx["remediation_analysis"])
            if "environment_configuration" in ctx:
                enriched.setdefault("environment_configuration", ctx["environment_configuration"])

    finding_cve = _prototype_finding_cve(finding)

    evaluation = sidecars.get("evaluation")
    remediation = sidecars.get("remediation")
    configuration = sidecars.get("configuration")
    validation = sidecars.get("validation")

    contextual_cve = (
        _prototype_sidecar_cve(evaluation)
        or _prototype_sidecar_cve(remediation)
    )

    # A contextual analysis must only be attached to the matching CVE.
    # This is essential when Trivy has many findings in one report.
    if contextual_cve and finding_cve == contextual_cve:
        if evaluation is not None:
            enriched.setdefault("cve_evaluation", evaluation)

        if remediation is not None:
            enriched.setdefault("remediation_analysis", remediation)

        if configuration is not None:
            enriched.setdefault(
                "environment_configuration",
                configuration
            )

        if validation is not None:
            enriched.setdefault(
                "remediation_validation",
                validation
            )

    return enriched


