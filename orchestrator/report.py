def render_condition(condition):
    """
    Render one CVE condition.

    Supports structures such as:

    {
        "condition": "...",
        "status": "CONFIRMED",
        "reason": "..."
    }

    or:

    {
        "name": "...",
        "status": "...",
        "reason": "..."
    }
    """

    if not isinstance(condition, dict):
        return f"""
        <div class="condition-row">
            <div>
                {safe_text(condition)}
            </div>
        </div>
        """

    name = (
        condition.get("condition")
        or condition.get("name")
        or condition.get("id")
        or "Condition"
    )

    status = condition.get(
        "status",
        "UNKNOWN"
    )

    reason = condition.get(
        "reason"
    )

    return f"""
    <div class="condition-row">

        <div class="condition-main">

            <div class="condition-name">
                {safe_text(name)}
            </div>

            {
                f'<div class="condition-reason">'
                f'{safe_text(reason)}'
                f'</div>'
                if reason
                else ""
            }

        </div>

        <div>
            {status_badge(status)}
        </div>

    </div>
    """


def render_conditions(conditions):
    if not conditions:
        return """
        <p class="muted">
            No detailed CVE conditions were supplied.
        </p>
        """

    html = '<div class="conditions">'

    for condition in conditions:
        html += render_condition(condition)

    html += "</div>"

    return html


