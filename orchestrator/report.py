def safe_text(value, default="N/A"):
    if value is None:
        return default

    if isinstance(value, bool):
        return str(value)

    if isinstance(value, (dict, list)):
        return escape(
            json.dumps(
                value,
                indent=2,
                ensure_ascii=False
            )
        )

    return escape(str(value))


def render_list(items, empty_text="No information available."):
    if not items:
        return f'<p class="muted">{escape(empty_text)}</p>'

    html = "<ul>"

    for item in items:
        if isinstance(item, dict):
            html += "<li>"

            for key, value in item.items():
                html += (
                    f"<b>{escape(str(key))}:</b> "
                    f"{safe_text(value)}<br>"
                )

            html += "</li>"

        else:
            html += f"<li>{safe_text(item)}</li>"

    html += "</ul>"

    return html


def status_class(status):
    value = str(status or "").upper()

    if value in [
        "CONFIRMED",
        "CONFIRMED_TRUE",
        "SATISFIED",
        "SUCCESSFUL",
        "PASS",
        "PASSED",
        "PATCHED",
        "MITIGATED",
        "NOT_AFFECTED",
        "NO_REMEDIATION",
        "REVIEWED",
        "LOW",
        "INFORMATIONAL"
    ]:
        return "status-success"

    val = str(status).upper().strip().replace(" ", "_")

    if val in [
        "NOT_PATCHED",
        "UNSUCCESSFUL",
        "FAILED",
        "FAIL",
        "REJECTED",
        "CRITICAL",
        "REMEDIATE_NOW",
        "REMEDIATION_REQUIRED",
        "LISTED",
        "YES",
        "LISTED_IN_CISA_KEV",
        "HIGH_RELEVANCE_SIGNAL"
    ]:
        return "status-danger"

    if val in [
        "UNKNOWN",
        "NEEDS_REVIEW",
        "REVIEW_REQUIRED",
        "REMEDIATE",
        "PENDING",
        "RISK_ACCEPTED",
        "UNDETERMINED",
        "NOT_DYNAMICALLY_CONFIRMED",
        "MODERATE_RELEVANCE",
        "HIGH",
        "MEDIUM"
    ]:
        return "status-warning"

    if val in [
        "EPSS_AVAILABLE",
        "AVAILABLE"
    ]:
        return "status-info"

    return "status-neutral"


def status_badge(status):
    if status is None:
        status = "UNKNOWN"

    s_str = str(status).strip()
    val_norm = s_str.upper().replace("_", " ")

    if val_norm in ("LISTED IN CISA KEV", "LISTED"):
        display = "Listed in CISA KEV"
    elif val_norm in ("NOT IN CISA KEV", "NOT IN KEV"):
        display = "Not in CISA KEV"
    elif val_norm in ("EPSS AVAILABLE", "AVAILABLE"):
        display = "EPSS Available"
    elif val_norm in ("EPSS UNAVAILABLE", "UNAVAILABLE"):
        display = "EPSS Unavailable"
    else:
        display = s_str.replace("_", " ").upper()

    css = status_class(status)

    return (
        f'<span class="status-badge {css}">'
        f'{escape(display)}'
        f'</span>'
    )


